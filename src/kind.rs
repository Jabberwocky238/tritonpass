impl TryFrom<&str> for Kind {
    type Error = ();
    fn try_from(s: &str) -> Result<Self, ()> {
        Self::TABLE.binary_search_by(|(_, n)| (*n).cmp(s)).map(|i| Self::TABLE[i].0).map_err(|_| ())
    }
}

impl From<Kind> for &'static str {
    fn from(k: Kind) -> Self {
        k.name()
    }
}

/// op 名的方言前缀（未登记的 op 也按前缀认）。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Namespace {
    Arith,
    Math,
    Other,
}

impl From<&str> for Namespace {
    fn from(name: &str) -> Self {
        match name.split_once('.').map(|(d, _)| d) {
            Some("arith") => Self::Arith,
            Some("math") => Self::Math,
            _ => Self::Other,
        }
    }
}
